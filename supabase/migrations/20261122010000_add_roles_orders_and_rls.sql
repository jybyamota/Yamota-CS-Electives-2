-- Role and profile tables
create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  role text not null unique
);

insert into public.roles (role) values ('customer'), ('admin')
on conflict (role) do nothing;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  email text,
  firstname text,
  lastname text,
  role_id bigint not null references public.roles(id),
  constraint profiles_firstname_required check (firstname is null or char_length(firstname) > 0),
  constraint profiles_lastname_required check (lastname is null or char_length(lastname) > 0)
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete restrict,
  status text not null default 'processing',
  total numeric(12, 2) not null default 0,
  constraint orders_status_allowed check (status in ('processing', 'completed', 'cancelled')),
  constraint orders_total_non_negative check (total >= 0)
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  unit_price numeric(12, 2) not null,
  quantity integer not null,
  constraint order_items_quantity_positive check (quantity > 0),
  constraint order_items_price_non_negative check (unit_price >= 0)
);

create index if not exists orders_user_id_created_at_idx
  on public.orders(user_id, created_at desc);
create index if not exists order_items_order_id_idx
  on public.order_items(order_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer_role_id bigint;
begin
  select r.id into customer_role_id
  from public.roles r
  where r.role = 'customer';

  insert into public.profiles (id, email, firstname, lastname, role_id)
  values (
    new.id,
    new.email,
    nullif(trim(coalesce(new.raw_user_meta_data->>'first_name', new.raw_user_meta_data->>'given_name', '')), ''),
    nullif(trim(coalesce(new.raw_user_meta_data->>'last_name', new.raw_user_meta_data->>'family_name', '')), ''),
    customer_role_id
  )
  on conflict (id) do update
  set email = excluded.email;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid()
      and r.role = 'admin'
  );
$$;

create or replace function public.prevent_profile_role_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.role_id is distinct from old.role_id and not public.is_admin() then
    raise exception 'Only an admin may change a profile role';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_prevent_role_change on public.profiles;
create trigger profiles_prevent_role_change
before update on public.profiles
for each row
execute function public.prevent_profile_role_change();

create or replace function public.checkout(p_items jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id bigint;
  v_total numeric(12, 2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Cart is empty';
  end if;

  insert into public.orders (user_id, status, total)
  values (auth.uid(), 'processing', 0)
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_quantity := (v_item->>'quantity')::integer;
    if v_quantity is null or v_quantity <= 0 then
      raise exception 'Quantity must be a positive whole number';
    end if;

    select * into v_product
    from public.products
    where id = (v_item->>'product_id')::bigint
    for update;

    if v_product.id is null then
      raise exception 'Product not found';
    end if;
    if v_product.stock < v_quantity then
      raise exception 'Insufficient stock for %', v_product.name;
    end if;

    insert into public.order_items (order_id, product_id, unit_price, quantity)
    values (v_order_id, v_product.id, v_product.price, v_quantity);

    update public.products
    set stock = stock - v_quantity
    where id = v_product.id;

    v_total := v_total + (v_product.price * v_quantity);
  end loop;

  update public.orders
  set total = v_total
  where id = v_order_id;

  return v_order_id;
end;
$$;

