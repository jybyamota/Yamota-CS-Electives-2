drop policy if exists "Public categories are readable" on public.categories;
drop policy if exists "Public categories can be inserted" on public.categories;
drop policy if exists "Public categories can be updated" on public.categories;
drop policy if exists "Public categories can be deleted" on public.categories;
drop policy if exists "Public products are readable" on public.products;
drop policy if exists "Public products can be inserted" on public.products;
drop policy if exists "Public products can be updated" on public.products;
drop policy if exists "Public products can be deleted" on public.products;

create policy "Categories are public read"
on public.categories for select to anon, authenticated using (true);
create policy "Admins manage categories"
on public.categories for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Products are public read"
on public.products for select to anon, authenticated using (true);
create policy "Admins manage products"
on public.products for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Customers read own profile"
on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());
create policy "Customers update own profile"
on public.profiles for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

create policy "Roles are readable"
on public.roles for select to authenticated using (true);

create policy "Customers read own orders"
on public.orders for select to authenticated
using (user_id = auth.uid() or public.is_admin());
create policy "Admins update orders"
on public.orders for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Customers read own order items"
on public.order_items for select to authenticated
using (
  exists (
    select 1 from public.orders o
    where o.id = order_id
      and (o.user_id = auth.uid() or public.is_admin())
  )
);

